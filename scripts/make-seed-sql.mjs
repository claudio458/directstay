// Generates supabase/seed.sql from src/data/seed.ts so DB demo data matches the browser demo.
// Usage: node scripts/make-seed-sql.mjs
import { build } from "esbuild";
import { writeFileSync } from "fs";
import path from "path";

const out = path.resolve("node_modules/.cache/seed.mjs");
await build({ entryPoints: ["src/data/seed.ts"], bundle: true, format: "esm", platform: "node", outfile: out, alias: { "@": path.resolve("src") }, logLevel: "error" });
const s = await import(out + "?" + Date.now());

const q = (v) => v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : Array.isArray(v) ? `array[${v.map(q).join(",")}]::text[]` : `'${String(v).replace(/'/g, "''")}'`;
const ins = (table, rows) => rows.length ? `insert into public.${table} (${Object.keys(rows[0]).join(", ")}) values\n${rows.map((r) => "  (" + Object.values(r).map(q).join(", ") + ")").join(",\n")};\n` : "";

let sql = "-- Generated by scripts/make-seed-sql.mjs. Dates are relative to the day it was generated.\n";
sql += ins("regions", s.regions);
sql += ins("organizations", s.organizations.map((o) => ({ id: o.id, name: o.name, type: o.type, city: o.city, country: o.country, verified: o.verified, email: o.email, phone: o.phone ?? null, website: o.website ?? null, bio: o.bio ?? null })));
sql += ins("properties", s.properties.map(({ calendar: c, created_at, ...p }) => ({
  id: p.id, slug: p.slug, organization_id: p.organization_id, region_id: p.region_id, title: p.title, city: p.city, area: p.area ?? null, type: p.type,
  size_m2: p.size_m2 ?? null, bedrooms: p.bedrooms, bathrooms: p.bathrooms, max_guests: p.max_guests, min_months: p.min_months, max_months: p.max_months,
  monthly_price: p.monthly_price ?? null, utilities_included: p.utilities_included, agent_commission_pct: p.agent_commission_pct ?? null,
  description: p.description, amenities: p.amenities, photos: p.photos, visibility: p.visibility, status: p.status,
  lat: p.lat ?? null, lng: p.lng ?? null, listing_source: p.listing_source, external_id: p.external_id ?? null, mirror_content: p.mirror_content, price_mode: p.price_mode, source_nightly_rate: p.source_nightly_rate ?? null, source_monthly_rate: p.source_monthly_rate ?? null,
  calendar_type: c.type, ical_url: c.ical_url ?? null, pms_provider: c.pms_provider ?? null, pms_listing_id: c.pms_listing_id ?? null, sync_status: c.sync_status,
})));
sql += ins("availability_blocks", s.blocks.map((b) => ({ property_id: b.property_id, start_date: b.start_date, end_date: b.end_date, source: b.source, summary: b.summary ?? null })));
writeFileSync("supabase/seed.sql", sql);
console.log("wrote supabase/seed.sql");
